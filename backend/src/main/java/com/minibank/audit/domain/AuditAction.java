package com.minibank.audit.domain;

/**
 * The catalogue of auditable actions.
 *
 * <p>An enum rather than free text: it keeps the values greppable, makes the audit query API
 * type-safe, and stops the same event being recorded under three different spellings.
 */
public enum AuditAction {
    // Authentication
    LOGIN_SUCCESS,
    LOGIN_FAILED,
    LOGOUT,
    TOKEN_REFRESHED,
    TOKEN_REUSE_DETECTED,
    ACCOUNT_LOCKED,
    PASSWORD_CHANGED,
    USER_REGISTERED,
    PROFILE_UPDATED,

    // Verification
    PHONE_VERIFICATION_REQUESTED,
    PHONE_VERIFIED,
    EMAIL_VERIFICATION_REQUESTED,
    EMAIL_VERIFIED,
    OTP_FAILED,
    OTP_EXPIRED,
    PASSWORD_LOGIN,
    PHONE_LOGIN,

    // Accounts
    ACCOUNT_CREATED,
    ACCOUNT_FROZEN,
    ACCOUNT_UNFROZEN,
    ACCOUNT_CLOSED,
    DEPOSIT_COMPLETED,
    TOP_UP_COMPLETED,

    // Transfers
    TRANSFER_CREATED,
    TRANSFER_COMPLETED,
    TRANSFER_FAILED,
    TRANSFER_FLAGGED_FOR_REVIEW,
    TRANSFER_BLOCKED_BY_RISK,
    TRANSFER_APPROVED,
    TRANSFER_REJECTED,
    TRANSFER_REVERSED,
    IDEMPOTENT_REPLAY,

    // Beneficiaries
    BENEFICIARY_CREATED,
    BENEFICIARY_DELETED,

    // Cards
    CARD_ISSUED,
    CARD_FROZEN,
    CARD_UNFROZEN,
    CARD_CANCELLED,
    CARD_UPDATED,
    CARD_LIMITS_UPDATED,
    CARD_CONTROLS_UPDATED,
    CARD_DETAILS_REVEALED,

    // Savings
    SAVINGS_GOAL_CREATED,
    SAVINGS_GOAL_UPDATED,
    SAVINGS_GOAL_ARCHIVED,
    SAVINGS_CONTRIBUTION,
    SAVINGS_WITHDRAWAL,

    // Budgets
    BUDGET_SET,
    BUDGET_DELETED,

    // Standing orders
    SCHEDULED_TRANSFER_CREATED,
    SCHEDULED_TRANSFER_UPDATED,
    SCHEDULED_TRANSFER_PAUSED,
    SCHEDULED_TRANSFER_RESUMED,
    SCHEDULED_TRANSFER_CANCELLED,
    SCHEDULED_TRANSFER_EXECUTED,
    SCHEDULED_TRANSFER_EXECUTION_FAILED,

    // Money requests
    MONEY_REQUEST_CREATED,
    MONEY_REQUEST_PAID,
    MONEY_REQUEST_DECLINED,
    MONEY_REQUEST_CANCELLED,

    // Sessions
    SESSION_REVOKED,
    ALL_SESSIONS_REVOKED,
    PASSWORD_RESET_REQUESTED,
    PASSWORD_RESET_COMPLETED,

    // Support
    SUPPORT_TICKET_OPENED,
    SUPPORT_TICKET_REPLIED,
    SUPPORT_TICKET_CLOSED,

    // Administration
    USER_STATUS_CHANGED,
    TRANSFER_LIMITS_UPDATED
}
